static int g_lang = 0;

void SetLang(int mode) { g_lang = mode == 1 ? 1 : 0; }

int GetLang() { return g_lang; }

const wchar_t* Tr(const wchar_t* zh) {
  if (g_lang == 0 || zh == nullptr) return zh;
  static const std::unordered_map<std::wstring, const wchar_t*> dict = []() {
    std::unordered_map<std::wstring, const wchar_t*> m;
    for (const LangPair& p : kPairs) m.emplace(p.zh, p.en);
    return m;
  }();
  auto it = dict.find(zh);
  if (it == dict.end()) return zh;
  return it->second;
}

